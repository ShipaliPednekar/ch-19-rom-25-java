class Hacker {
    
    static String name;
    static String alias;
    static byte skillLevel;
    static short age;
    static int hacksDone;
    static long hackerId;
    static float successRate;
    static double bountyAmount;
    static char dangerLevel;
    static boolean isActive;
    static String country;
    static boolean isBlackHat;
    static int languagesKnown;
    static short yearsOfExperience;
    static float anonymityScore;
   

    public String getName() {
        return name;
    }

    public int getHacksDone() {
        return hacksDone;
    }

    public boolean getIsActive() {
        return isActive;
    }

    public double getBountyAmount() {
        return bountyAmount;
    }

    public byte getSkillLevel() {
        return skillLevel;
    }

    public float getAnonymityScore() {
        return anonymityScore;
    }
}
