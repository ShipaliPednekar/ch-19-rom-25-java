class DisneyLand {
   
    static String parkName;
    static String location;
    static byte numberOfZones;
    static short numberOfRides;
    static int dailyVisitors;
    static long parkId;
    static float entryFee;
    static double annualRevenue;
    static char category;
    static boolean isOpen;
    static String mainAttraction;
    static boolean hasFireworks;
    static int staffCount;
    static short areaInAcres;
    static float rating;

   

    public String getParkName() {
        return parkName;
    }

    public int getDailyVisitors() {
        return dailyVisitors;
    }

    public boolean getIsOpen() {
        return isOpen;
    }

    public double getAnnualRevenue() {
        return annualRevenue;
    }

    public byte getNumberOfZones() {
        return numberOfZones;
    }

    public float getRating() {
        return rating;
    }
}
