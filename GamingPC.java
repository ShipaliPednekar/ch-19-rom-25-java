class GamingPC {
    
    static String brand;
    static String processor;
    static byte ramInGB;
    static short ssdInGB;
    static int graphicsCardMemory;
    static long serialNumber;
    static float cpuClockSpeed;
    static double price;
    static char performanceGrade;
    static boolean isRGBEnabled;
    static String cabinetColor;
    static boolean isAvailable;
    static int usbPorts;
    static short fansCount;
    static float temperature;

    

    public String getBrand() {
        return brand;
    }

    public double getPrice() {
        return price;
    }

    public boolean getIsRGBEnabled() {
        return isRGBEnabled;
    }

    public int getGraphicsCardMemory() {
        return graphicsCardMemory;
    }

    public byte getRamInGB() {
        return ramInGB;
    }

    public float getCpuClockSpeed() {
        return cpuClockSpeed;
    }
}
