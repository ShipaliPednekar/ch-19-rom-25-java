class River {
    
    static String name;
    static String origin;
    static byte pollutionLevel;
    static short depth;
    static int length;
    static long riverCode;
    static float flowRate;
    static double waterVolume;
    static char qualityGrade;
    static boolean isNavigable;
    static String country;
    static boolean isPerennial;
    static int tributariesCount;
    static short width;
    static float temperature;


    public String getName() {
        return name;
    }

    public int getLength() {
        return length;
    }

    public boolean getIsNavigable() {
        return isNavigable;
    }

    public double getWaterVolume() {
        return waterVolume;
    }

    public byte getPollutionLevel() {
        return pollutionLevel;
    }

    public float getTemperature() {
        return temperature;
    }
}
